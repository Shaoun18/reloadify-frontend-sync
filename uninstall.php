<?php


if ( ! defined( 'WP_UNINSTALL_PLUGIN' ) ) {
	exit;
}

/* ---------------- Uninstall Cleanup ---------------- */

function reloadify_uninstall_cleanup_current_site() {
	// Scheduled events are plugin footprint, not user data: they go whatever
	// the "delete data" choice is. wp_unschedule_hook() also removes the
	// per-video events, which carry an attachment ID argument that
	// wp_next_scheduled( $hook ) can't match.
	wp_unschedule_hook( 'reloadify_media_backfill_batch' );
	wp_unschedule_hook( 'reloadify_media_backfill_video_batch' );
	wp_unschedule_hook( 'reloadify_media_compress_video' );
	wp_unschedule_hook( 'reloadify_cleanup_transients' );

	// Checked per site: on multisite each site has its own choice, and the
	// main site's setting must not decide for every other site.
	if ( ! get_option( 'reloadify_delete_data_on_uninstall', false ) ) {
		return;
	}

	// What to remove, group by group (Settings > Delete Data on Uninstall).
	// Sites that switched the master option on before the groups existed have
	// no stored choice and get the defaults: settings and cached files.
	$scope = get_option( 'reloadify_cleanup_scope', [] );
	$scope = is_array( $scope ) ? $scope : [];
	$scope = array_merge(
		[
			'settings' => true,
			'cache'    => true,
			'storage'  => false,
			'logs'     => false,
		],
		$scope
	);

	if ( ! empty( $scope['settings'] ) ) {
		delete_option( 'reloadify_settings' );
		delete_option( 'reloadify_performance' );
		delete_option( 'reloadify_speed_boost_enabled' );
		delete_option( 'reloadify_speed_options' );
		delete_option( 'reloadify_media_optimize_enabled' );
		delete_option( 'reloadify_media_format_preference' );
		delete_option( 'reloadify_media_quality' );
		delete_option( 'reloadify_extras_settings' );
		delete_option( 'reloadify_cleanup_scope' );
		delete_option( 'reloadify_delete_data_on_uninstall' );
	}

	if ( ! empty( $scope['logs'] ) ) {
		delete_option( 'reloadify_last_site_update' );
		delete_transient( 'reloadify_media_totals' );
	}

	if ( ! empty( $scope['storage'] ) ) {
		// Per-attachment optimization records written by Media Optimization.
		// The optimized files themselves are site content and stay.
		delete_post_meta_by_key( '_reloadify_media_optimized' );
		delete_post_meta_by_key( '_reloadify_media_video_optimized' );
		delete_post_meta_by_key( '_reloadify_media_stats' );
	}

	if ( empty( $scope['cache'] ) ) {
		return;
	}

	delete_option( 'reloadify_server_rules_rev' );
	delete_option( 'reloadify_speed_cache_rev' );

	$upload = wp_upload_dir();
	if ( empty( $upload['basedir'] ) ) {
		return;
	}

	require_once ABSPATH . 'wp-admin/includes/file.php';
	WP_Filesystem();

	global $wp_filesystem;
	if ( ! $wp_filesystem ) {
		return;
	}

	// The reload timestamp folder and the Speed Boost minification cache are
	// both generated by this plugin.
	$reloadify_generated_dirs = [
		trailingslashit( $upload['basedir'] ) . 'reloadify-reload',
		trailingslashit( $upload['basedir'] ) . 'reloadify-minify',
		trailingslashit( $upload['basedir'] ) . 'reloadify-preview',
	];

	foreach ( $reloadify_generated_dirs as $dir ) {
		if ( is_dir( $dir ) ) {
			$wp_filesystem->delete( $dir, true );
		}
	}
}

// The Speed Boost block in .htaccess is plugin footprint too -- remove it
// whatever the "delete data" choice is. (Single sites only; the plugin never
// writes it on multisite.)
if ( ! is_multisite() ) {
	require_once ABSPATH . 'wp-admin/includes/file.php';
	require_once ABSPATH . 'wp-admin/includes/misc.php';

	$reloadify_htaccess = trailingslashit( get_home_path() ) . '.htaccess';

	if ( file_exists( $reloadify_htaccess ) && wp_is_writable( $reloadify_htaccess ) && extract_from_markers( $reloadify_htaccess, 'Reloadify Speed Boost' ) ) {
		insert_with_markers( $reloadify_htaccess, 'Reloadify Speed Boost', [] );
	}
}

if ( is_multisite() ) {
	$reloadify_site_ids = get_sites( [ 'fields' => 'ids' ] );

	foreach ( $reloadify_site_ids as $reloadify_site_id ) {
		switch_to_blog( $reloadify_site_id );
		reloadify_uninstall_cleanup_current_site();
		restore_current_blog();
	}
} else {
	reloadify_uninstall_cleanup_current_site();
}
